#!/usr/bin/env python3
"""Generates an SQL patch that fills the empty faction lists of our NPCs from the Quarm database.

Thousands of npc_faction rows of the dump are shells: no primary faction, no entry. Their NPCs
(the Bashers of Grobb, merchants of Qeynos, Steel Warriors...) think nothing of anybody: they con
indifferent, do not help the players they should like and killing them moves no faction.
For each such list used by a spawned NPC, the NPC of the same zone (id / 1000) and name in Quarm (quarm_ref, see
README.md) gives its primary faction and its entries; factions are matched by name (the ids differ).
A list whose NPCs do not agree on one Quarm list is left alone. Plain rows: the patch needs no quarm_ref.

Usage: gen_npc_factions.py <patch number> > sql/patches/NNN_npc_faction_lists.sql
Environment: EQC_DB_USER, EQC_DB_PASS, EQC_DB_NAME (eqc / eqc / eqclassic), QUARM_DB (quarm_ref).
"""
import os
import re
import subprocess
import sys

USER = os.environ.get('EQC_DB_USER', 'eqc')
PASS = os.environ.get('EQC_DB_PASS', 'eqc')
OURS = os.environ.get('EQC_DB_NAME', 'eqclassic')
QUARM = os.environ.get('QUARM_DB', 'quarm_ref')


def rows(sql):
    out = subprocess.run(['mysql', '--skip-ssl', '-u' + USER, '-p' + PASS, '-N', '-B', '--raw', OURS, '-e', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines()]


def key(name):
    """'The Freeport Militia' and 'Freeport Militia', 'Death Fist Orcs' and 'Deathfist Orcs' are one faction."""
    k = re.sub(r'[^a-z0-9]', '', name.lower())
    k = k[3:] if k.startswith('the') else k
    return {'oggokresident': 'oggokresidents'}.get(k, k)


def main():
    number = sys.argv[1]
    ours_by_name = {}
    for fid, name in rows("SELECT id, name FROM faction_list ORDER BY id DESC"):
        ours_by_name[key(name)] = fid		# the lowest id of a name wins
    quarm_name = {fid: key(name) for fid, name in rows("SELECT id, name FROM %s.faction_list" % QUARM)}

    # our empty lists used by a spawned NPC -> the Quarm lists of those NPCs
    pairs = rows(
        "SELECT DISTINCT f.id, qn.npc_faction_id FROM (SELECT DISTINCT npcID AS id FROM spawnentry) u "
        "JOIN npc_types_without n ON n.id = u.id JOIN npc_faction f ON f.id = n.npc_faction_id "
        "JOIN %s.npc_types qn ON qn.id DIV 1000 = n.id DIV 1000 AND REPLACE(LOWER(qn.name), '#', '') = REPLACE(LOWER(n.name), '#', '') "
        "WHERE f.primaryfaction = 0 AND qn.npc_faction_id > 0 AND qn.id < 1000000 "
        "AND NOT EXISTS (SELECT 1 FROM npc_faction_entries e WHERE e.npc_faction_id = f.id) ORDER BY f.id" % QUARM)
    wanted = {}
    for ours, theirs in pairs:
        wanted.setdefault(ours, set()).add(theirs)
    qprimary = {r[0]: r[1] for r in rows("SELECT id, primaryfaction FROM %s.npc_faction" % QUARM)}
    qentries = {}
    for lid, fid, value, npc_value in rows("SELECT npc_faction_id, faction_id, value, npc_value FROM %s.npc_faction_entries ORDER BY 1, 2" % QUARM):
        qentries.setdefault(lid, []).append((fid, value, npc_value))

    lists, entries, split, unknown = [], [], 0, set()
    for ours in sorted(wanted, key=int):
        if len(wanted[ours]) != 1:
            split += 1
            continue
        theirs = next(iter(wanted[ours]))
        prim = ours_by_name.get(quarm_name.get(qprimary.get(theirs, '0'), ''), '0')
        mine = []
        for fid, value, npc_value in qentries.get(theirs, []):
            o = ours_by_name.get(quarm_name.get(fid, ''))
            if o is None:
                unknown.add(quarm_name.get(fid, fid))
                continue
            mine.append((ours, o, value, npc_value))
        if prim == '0' and not mine:
            continue
        lists.append((ours, prim))
        entries += mine

    w = print
    w('-- %s: the empty faction lists of spawned NPCs, filled from Quarm.' % number)
    w('--')
    w('-- %d npc_faction rows of the dump had no primary faction and no entry (the Bashers of Grobb, merchants,' % len(lists))
    w('-- guards, guild masters...): their NPCs conned indifferent to everybody, never helped a player they should like,')
    w('-- and killing them moved no faction. Each takes the primary faction and the entries (%d in all) of the Quarm NPC' % len(entries))
    w('-- of the same zone and name; factions are matched by name. Generated by tools/npc_stats/gen_npc_factions.py')
    w('-- (regenerate rather than edit; generate before applying: it reads the live tables).')
    w('-- %d lists whose NPCs have different lists in Quarm are left as they were.' % split)
    w('--')
    w('-- The rows changed are kept in npc_faction_before_%s. To restore: delete the npc_faction_entries rows of those' % number)
    w('-- lists and put the npc_faction rows back. Idempotent.')
    w('')
    w('CREATE TABLE IF NOT EXISTS npc_faction_before_%s LIKE npc_faction;' % number)
    ids = [l[0] for l in lists]
    for i in range(0, len(ids), 500):
        w('INSERT IGNORE INTO npc_faction_before_%s SELECT * FROM npc_faction WHERE id IN (%s);' % (number, ','.join(ids[i:i + 500])))
    w('')
    by_prim = {}
    for ours, prim in lists:
        by_prim.setdefault(prim, []).append(ours)
    for prim in sorted(by_prim, key=int):
        if prim != '0':
            w('UPDATE npc_faction SET primaryfaction = %s WHERE id IN (%s);' % (prim, ','.join(by_prim[prim])))
    w('')
    for i in range(0, len(entries), 500):
        w('REPLACE INTO npc_faction_entries (npc_faction_id, faction_id, value, npc_value) VALUES')
        w(',\n'.join('(%s, %s, %s, %s)' % e for e in entries[i:i + 500]) + ';')
    print('%d lists, %d entries, %d split lists skipped, Quarm factions we do not have: %s' % (
        len(lists), len(entries), split, ', '.join(sorted(map(str, unknown))) or 'none'), file=sys.stderr)


if __name__ == '__main__':
    main()
