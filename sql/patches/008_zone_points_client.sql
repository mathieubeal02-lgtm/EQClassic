-- 008: zone points numbered as the client's zone files number them (OP_SendZonePoints).
--
-- The Trilogy client zones by itself through the zone lines and teleport pads of its zone files; a line
-- that names a zone point number is looked up in the list the zone sends at zone-in (Harakiri found
-- the packet, his rev. 719). Our zone_points table has no such number, so the list comes from the
-- Quarm (EQMacEmu) database, whose zone ids are ours (185 of 185 shared zones agree): its non-virtual
-- points of the zones we have. 999999 in a target coordinate keeps the player's own; heading 999 too.
--
-- Zones send nothing while this table is missing or has no row for them. Idempotent.
CREATE TABLE IF NOT EXISTS zone_points_client (
	zone varchar(16) NOT NULL,
	number smallint unsigned NOT NULL,
	target_zone_id int unsigned NOT NULL,
	target_x float NOT NULL,
	target_y float NOT NULL,
	target_z float NOT NULL,
	target_heading float NOT NULL,
	PRIMARY KEY (zone, number)
);

